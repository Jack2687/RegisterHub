"""
Universal Account Ledger Exporter.
Converts accounts.txt into standard CSV, JSON, and Bitwarden/1Password importable vaults.
"""
import csv
import io
import json
from pathlib import Path
from datetime import datetime
from typing import List, Dict, Any

from core.locks import atomic_write_text_safe, interprocess_file_lock


def parse_accounts_file(filepath: Path) -> List[Dict[str, str]]:
    """Parse 'email----password----username[----api_key]' accounts file."""
    accounts = []
    if not filepath.exists():
        return accounts

    with open(filepath, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "----" not in line:
                continue
            parts = line.split("----")
            email = parts[0].strip() if len(parts) > 0 else ""
            pwd = parts[1].strip() if len(parts) > 1 else ""
            user = parts[2].strip() if len(parts) > 2 else ""
            api_key = parts[3].strip() if len(parts) > 3 else ""
            # Backward-compat for legacy 3-col lines where api_key was stored in pwd
            if not api_key and pwd.startswith(("sk-", "gsk_", "rk_", "api_")):
                api_key = pwd
            accounts.append({
                "email": email,
                "password": pwd,
                "username": user,
                "api_key": api_key,
            })
    return accounts


def export_to_csv(accounts: List[Dict[str, str]], out_path: Path):
    """Export accounts as a clean CSV with standard headers (cross-process locked atomic write)."""
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=["email", "password", "username", "api_key", "exported_at"], lineterminator="\n")
    writer.writeheader()
    now = datetime.now().isoformat()
    for acc in accounts:
        writer.writerow({
            "email": acc.get("email", ""),
            "password": acc.get("password", ""),
            "username": acc.get("username", ""),
            "api_key": acc.get("api_key", ""),
            "exported_at": now
        })
    with interprocess_file_lock(out_path):
        atomic_write_text_safe(out_path, buf.getvalue())


def export_to_json(accounts: List[Dict[str, str]], out_path: Path):
    """Export accounts as structured JSON (cross-process locked atomic write)."""
    now = datetime.now().isoformat()
    data = {
        "metadata": {
            "total_accounts": len(accounts),
            "exported_at": now
        },
        "accounts": accounts
    }
    with interprocess_file_lock(out_path):
        atomic_write_text_safe(out_path, json.dumps(data, ensure_ascii=False, indent=2))


def export_to_bitwarden(accounts: List[Dict[str, str]], out_path: Path):
    """
    Export accounts matching official Bitwarden / 1Password import specification (cross-process locked atomic write):
    folder,favorite,type,name,notes,fields,reprompt,login_uri,login_username,login_password,login_totp
    """
    fieldnames = [
        "folder", "favorite", "type", "name", "notes", "fields",
        "reprompt", "login_uri", "login_username", "login_password", "login_totp"
    ]
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=fieldnames, lineterminator="\n")
    writer.writeheader()
    for acc in accounts:
        name = acc["email"].split("@")[1] if "@" in acc["email"] else "RegisterHub Account"
        api_k = acc.get("api_key", "")
        note_extra = f" | API Key: {api_k}" if api_k else ""
        writer.writerow({
            "folder": "RegisterHub",
            "favorite": "0",
            "type": "login",
            "name": name,
            "notes": f"Generated by RegisterHub on {datetime.now().strftime('%Y-%m-%d')}{note_extra}",
            "fields": "",
            "reprompt": "0",
            "login_uri": "",
            "login_username": acc["email"] or acc["username"],
            "login_password": acc["password"],
            "login_totp": ""
        })
    with interprocess_file_lock(out_path):
        atomic_write_text_safe(out_path, buf.getvalue())


def run_export(fmt: str = "csv", input_file: str = "results/accounts.txt", out_dir: str = "results") -> Path:
    """Run export CLI orchestrator."""
    src = Path(input_file)
    accounts = parse_accounts_file(src)
    if not accounts:
        raise ValueError(f"No valid accounts found in {src}")

    target_dir = Path(out_dir)
    target_dir.mkdir(parents=True, exist_ok=True)
    fmt = fmt.lower().strip()

    if fmt == "json":
        out_path = target_dir / "accounts.json"
        export_to_json(accounts, out_path)
    elif fmt == "bitwarden":
        out_path = target_dir / "bitwarden_import.csv"
        export_to_bitwarden(accounts, out_path)
    else:
        out_path = target_dir / "accounts.csv"
        export_to_csv(accounts, out_path)

    return out_path
